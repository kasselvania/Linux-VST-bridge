def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        while block := f.read(1024*1024): h.update(block)
    return h.hexdigest()


def extract(archive, target):
    target.mkdir()
    with tarfile.open(archive) as tar:
        roots = {m.name.split('/')[0] for m in tar.getmembers()}
        if len(roots) != 1: raise ValueError('Source archive root')
        for member in tar:
            parts = member.name.split('/', 1)
            if len(parts) < 2 or not parts[1]: continue
            member.name = parts[1]
            tar.extract(member, target, filter='data')


def prepare(root, cache):
    root.mkdir(mode=0o700)
    inputs = root/'inputs'; inputs.mkdir()
    for name, (url, expected) in INPUTS.items():
        path = inputs/name
        if cache and (cache/name).exists(): shutil.copyfile(cache/name, path)
        else:
            with urllib.request.urlopen(url, timeout=60) as src, path.open('xb') as out:
                shutil.copyfileobj(src, out)
        if sha(path) != expected: raise ValueError('Source input changed: '+name)
    extract(inputs/'wine.tar.gz', root/'wine')
    extract(inputs/'ge.tar.gz', root/'ge')
    extract(inputs/'staging.tar.gz', root/'wine-staging')
    shutil.copyfile(inputs/'configure', root/'wine/configure')
    shutil.copyfile(inputs/'config.h.in', root/'wine/include/config.h.in')
    (root/'patches').symlink_to('ge/patches')
    shutil.copytree(root/'ge/wineopenxr', root/'wineopenxr')
    original = (root/'ge/patches/protonprep-valve-staging.sh').read_text()
    start = original.index('    echo "WINE: -WINEOPENXR-')
    end = original.index('\n    popd', start)
    body = original[start:end]
    # The pinned SDK performs these generation steps after applying our patches.
    body = body.replace('    autoreconf -f', '    : # generated by build.sh')
    body = body.replace('    ./tools/make_requests', '    : # generated by build.sh')
    preamble = '''#!/bin/bash
set -euo pipefail
apply_patch() { patch --batch -Np1 < "$1"; }
apply_all_in_dir() { for patch in "$1"/*.patch; do apply_patch "$patch"; done; }
cd "$(dirname "$0")/wineopenxr"
apply_all_in_dir "../patches/wineopenxr/"
cd ../wine
'''
    (root/'apply-ge.sh').write_text(preamble+body+'\n')
    with (root/'ge-patches.log').open('w') as log:
        subprocess.run(['bash', str(root/'apply-ge.sh')], stdout=log, stderr=subprocess.STDOUT, check=True)
    before = sha(root/'wine/dlls/winex11.drv/mouse.c')
    here = Path(__file__).resolve().parent
    for name in PATCHES:
        shutil.copyfile(here/name, root/name)
        subprocess.run(['patch','--batch','--fuzz=0','-p1','-i',str(root/name)], cwd=root/'wine', check=True)
    for name in ('mouse.c','touch_message_flags.h'):
        path=root/'wine/dlls/winex11.drv'/name
        path.write_text('/* Modified 2026-10-18 by Linux-VST-bridge: per-window touch routing and released-contact flags. */\n'+path.read_text())
    for name in ('build.py','test_touch_flags.c'):
        shutil.copyfile(here/name, root/name)
    (root/'build.sh').write_text(SCRIPT)
    (root/'cache').mkdir()
    return before


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--inputs',type=Path)
    args=parser.parse_args();root=args.output.resolve()
    before=prepare(root,args.inputs)
    source=root/'wine/dlls/winex11.drv'
    consumed={name:sha(source/name) for name in ('mouse.c','touch_message_flags.h')}
    subprocess.run(['docker','run','--rm','--name','lvb-ge-touch-builder',
        '--cpus','2','--cpuset-cpus','2,3','--memory','4g','--memory-swap','4g',
        '--pids-limit','256','--network','none','--user',f'{os.getuid()}:{os.getgid()}',
        '--entrypoint','/bin/sh','--volume',str(root)+':/work',SDK,'/work/build.sh'],check=True,timeout=3600)
    if any(sha(source/name)!=digest for name,digest in consumed.items()): raise ValueError('Touch source changed during build')
    artifact=root/'obj64/dlls/winex11.drv/winex11.so'
    header=artifact.read_bytes()[:20]
    if header[:6]!=b'\x7fELF\x02\x01' or int.from_bytes(header[18:20],'little')!=62: raise ValueError('Expected x86-64 ELF driver')
    record=dict(schema=1,wine=WINE,ge=GE,staging=STAGING,sdk=SDK,
        inputs={name:digest for name,(_,digest) in INPUTS.items()},
        ge_mouse_sha256=before,touch_sources=consumed,
        recipe_sha256=sha(root/'build.py'),build_script_sha256=sha(root/'build.sh'),
        ge_script_sha256=sha(root/'apply-ge.sh'),
        patches={name:sha(root/name) for name in PATCHES},
        mapping_test='passed',artifact=dict(path=str(artifact.relative_to(root)),sha256=sha(artifact),size=artifact.stat().st_size))
    (root/'build-manifest.json').write_text(json.dumps(record,indent=2,sort_keys=True)+'\n')
    print(json.dumps(record))

if __name__=='__main__': main()
